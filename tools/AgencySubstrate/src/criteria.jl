# Criteria of AGENCY-001 §3.1–§3.3, measured on the prototype substrate. Survival is a proxy (activity
# and life over the horizon), not a DC judgment at each time (AGENCY-001 §4).

"""Alive at the horizon: not dead, and some non-sensor unit active at each of the last steps."""
function alive(traj, s::Substrate, p::Params)
    last(traj).dead && return false
    all(st -> any(u -> st.active[u] && !is_sensor(s, u), 1:nunits(s)), traj[(end - p.alive_window + 1):end])
end

survives(s, p, sch; silenced=Set{Int}()) = alive(run_trajectory(s, p, sch; silenced), s, p)

"""Structure persists at the horizon: some connection still has positive strength."""
structure_persists(s, p, sch; silenced=Set{Int}()) = any(>(0), last(run_trajectory(s, p, sch; silenced)).strength)

"""Motors active at some step of the window (abundant resource, so starvation cannot decide it)."""
function choice(s, pc, sch, window; silenced=Set{Int}())
    traj = run_trajectory(s, pc, sch; silenced)
    Set(m for m in keys(s.motors) for t in window if traj[t + 1].active[m])
end

"""Actions differ between the two couplings of different value (the two choice schedules)."""
value_differentiated(s, pc, c, window) = choice(s, pc, c[1], window) != choice(s, pc, c[2], window)

"""
Value-tracking units, identified by measurement (AGENCY-001 §3.3, provisional): units whose silencing
changes the motor choice in exactly one of the two choice schedules. A unit whose silencing changes
both (such as the core of the system) is not value-tracking. Empty when the system is not
value-differentiated.
"""
function value_tracking_units(s, pc, c, window)
    value_differentiated(s, pc, c, window) || return Int[]
    base = [choice(s, pc, x, window) for x in c]
    [u for u in 1:nunits(s)
     if count(i -> choice(s, pc, c[i], window; silenced=Set([u])) != base[i], 1:2) == 1]
end

"""Survival with the value-tracking units strictly dominates survival without them (no threshold)."""
function value_needed(s, p, survival, T)
    isempty(T) && return false
    ablated = Set(T)
    intact = [survives(s, p, x) for x in survival]
    without = [survives(s, p, x; silenced=ablated) for x in survival]
    any(i -> intact[i] && !without[i], eachindex(survival)) && all(i -> !without[i] || intact[i], eachindex(survival))
end

sensor_units(s::Substrate) = Set(u for u in 1:nunits(s) if is_sensor(s, u))

"""
The core κ: non-sensor units that stay active by themselves, with abundant resource and every sensor
silenced (no drive from the environment), over the last steps of the horizon. Stand-in for DC's
hSelf: the system must keep some of its own activity going (revision of 2026-10-09; the first version
took any persisting activity, which a stimulus-driven forager also has).
"""
function endogenous_core(s, pc, schedule)
    traj = run_trajectory(s, pc, schedule; silenced=sensor_units(s))
    tail = traj[(end - pc.alive_window + 1):end]
    all(st -> any(u -> st.active[u] && !is_sensor(s, u), 1:nunits(s)), tail) || return Int[]
    sort!(unique(u for st in tail for u in 1:nunits(s) if st.active[u] && !is_sensor(s, u)))
end

"""
The action passes through the core (stand-in for DC's hinge Act): silencing the core changes the
motor choice in both choice schedules.
"""
function core_enables_action(s, pc, c, window, core)
    isempty(core) && return false
    all(x -> choice(s, pc, x, window; silenced=Set(core)) != choice(s, pc, x, window), c)
end

"""
L3: without activity the structure persists under no schedule, and with its own activity alone
(sensors silenced, abundant resource) it persists under some schedule. Activity driven by the
environment does not count as the system's own (revision of 2026-10-09).
"""
function self_producing(s, p, pc, schedules)
    everything = Set(1:nunits(s))
    !any(x -> structure_persists(s, p, x; silenced=everything), schedules) &&
        any(x -> structure_persists(s, pc, x; silenced=sensor_units(s)), schedules)
end

"""
Deepened L3 (user decision of 2026-10-24): self-repair. Self-producing, and the connections each core
unit loses under damage are regenerated by the system's own activity. The damage is source silencing
only (P-04): with the sensors silenced, abundant resource and the first declared schedule, each core
unit `u` is silenced from the start for `smax * decay_period` steps (long enough for every connection
it sends to decay to nothing), then released, and the run goes on for `horizon` steps. The
constituents of `u` are its outgoing connections that persist under the system's own activity without
damage. Repaired: each of them is back (strength at least 1) at the end and the system is alive over
the last steps. Required for every core unit, and at least one core unit must have a constituent (so
that some damage is actually done).
"""
function self_repairing(s, p, pc, schedules)
    self_producing(s, p, pc, schedules) || return false
    sch = schedules[1]
    sensors = sensor_units(s)
    core = endogenous_core(s, pc, sch)
    isempty(core) && return false
    undamaged = last(run_trajectory(s, pc, sch; silenced=sensors)).strength
    damage = pc.smax * pc.decay_period
    any_constituent = false
    for u in core
        constituents = [k for (k, (src, _, _)) in enumerate(s.edges) if src == u && undamaged[k] > 0]
        any_constituent |= !isempty(constituents)
        st = initial_state(s, pc)
        tail = State[]
        for t in 1:(damage + pc.horizon)
            step!(st, s, pc, sch, t <= damage ? union(sensors, Set([u])) : sensors)
            t > damage + pc.horizon - pc.alive_window && push!(tail, deepcopy(st))
        end
        st.dead && return false
        all(x -> any(v -> x.active[v] && !is_sensor(s, v), 1:nunits(s)), tail) || return false
        all(k -> st.strength[k] >= 1, constituents) || return false
    end
    any_constituent
end

"""Every criterion and its diagnostics for one substrate."""
function evaluate(s::Substrate, setup)
    p, pc, c, w, surv = setup.params, setup.choice_params, setup.choice, setup.choice_window, setup.survival
    core = endogenous_core(s, pc, surv[1])
    measured = value_tracking_units(s, pc, c, w)
    # Core units are not ablated as value-tracking (user decision of 2026-10-24): silencing the core
    # can make survival depend on the ablation without any value-tracking being needed.
    T = setdiff(measured, core)
    alive_somewhere = any(x -> survives(s, p, x), surv)
    differentiated = value_differentiated(s, pc, c, w)
    needed = value_needed(s, p, surv, T)
    hinge = core_enables_action(s, pc, c, w, core)
    (; agency=!isempty(core) && hinge && alive_somewhere && differentiated && needed,
       self_producing=self_producing(s, p, pc, surv),
       self_repairing=self_repairing(s, p, pc, surv),
       core=[s.names[u] for u in core], core_enables_action=hinge,
       alive_somewhere, differentiated, value_needed=needed,
       value_tracking=[s.names[u] for u in T],
       value_tracking_measured=[s.names[u] for u in measured],
       choices=Dict(x.name => sort!([s.names[m] for m in choice(s, pc, x, w)]) for x in c),
       survival=Dict(x.name => survives(s, p, x) for x in surv),
       survival_without_tracking=isempty(T) ? Dict{String,Bool}() :
           Dict(x.name => survives(s, p, x; silenced=Set(T)) for x in surv))
end
